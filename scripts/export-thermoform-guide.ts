/** Illustrazioni ricavate dai triangoli reali del kit con filetti integrati. */
import {mkdirSync,writeFileSync} from 'node:fs';
import {loadManifold,Scope,toMeshData,type Part,type Manifold,type MeshData} from '@bdl/geometry';
import {build} from '../apps/thermoform/src/geometry.ts';
import {DEFAULTS} from '../apps/thermoform/src/params.ts';
const M=await loadManifold(),s=new Scope(),t=<T extends {delete():void}>(a:T)=>s.t(a);
const p={...DEFAULTS,shape:'round' as const,width:63,height:71},r=build(M,p);
const colors:Record<string,string>={front:'#ff621d',back:'#efbe60',female:'#477e98',male:'#7eaabe',cap:'#515e6c','bottom-clip':'#29a57c'};
const solid=(part:Part)=>{const mesh=new M.Mesh({numProp:3,vertProperties:part.mesh.positions,triVerts:part.mesh.indices});mesh.merge();return t(new M.Manifold(mesh));};
const actor=(id:string,m:Manifold|MeshData)=>{const mesh='volume' in m?toMeshData(m as Manifold):m as MeshData;return{id,color:colors[id]??'#477e98',positions:Array.from(mesh.positions),indices:Array.from(mesh.indices)};};
const a=Object.fromEntries(r.parts.map(part=>[part.id,solid(part)])),scenes:Record<string,unknown>={};
const scene=(name:string,items:ReturnType<typeof actor>[],eye=[-1,-1.6,1.1],arrows:number[][][]=[])=>scenes[name]={items,eye,arrows};
try{
 for(const part of r.parts)scene('part-'+part.id,[actor(part.id,a[part.id])]);
 scene('cap-under',[actor('cap',a.cap)],[-1,-1.6,-.9]);
 const neckBase=a.front.boundingBox().max[1]-8;
 const normalize=(m:Manifold)=>t(t(m.rotate([90,0,0])).translate([0,0,-neckBase]));
 const crop=t(t(M.Manifold.cube([16,16,14],true)).translate([0,0,4]));
 const ft=t(normalize(a.front).intersect(crop)),bt=t(normalize(t(a.back.scale([-1,1,-1]))).intersect(crop));
 scene('neck-separated',[actor('front',t(ft.translate([0,-4,0]))),actor('back',t(bt.translate([0,4,0])))],[-1,-1.6,1]);
 scene('neck-joined',[actor('front',ft),actor('back',bt)],[-1,-1.6,1]);
 scene('cap-down',[actor('front',ft),actor('back',bt),actor('cap',t(a.cap.translate([0,0,14])))],[-1.4,-1.6,.9],[[[0,0,14],[0,0,9]]]);
 const sectionBox=t(t(M.Manifold.cube([200,240,200],true)).translate([100,0,0]));
 const section=(m:Manifold)=>t(m.intersect(sectionBox));
 scene('closed',[actor('front',ft),actor('back',bt),actor('cap',section(a.cap))],[-1,-1.6,1]);
 const sheetZ=3+p.dome,closedZ=6+p.dome+p.sheet+p.clearance;
 const inverted=t(a.male.rotate([0,180,0]));
 const flatDown=t(t(a.front.scale([1,1,-1])).translate([0,0,sheetZ+p.sheet]));
 scene('exploded',[actor('female',a.female),actor('front',t(flatDown.translate([0,0,15]))),actor('male',t(inverted.translate([0,0,closedZ+45])))],[-1,-1.6,.75],[[[0,0,44],[0,0,39]],[[0,0,32],[0,0,26]]]);
 scene('position',[actor('female',a.female),actor('front',flatDown)],[-1,-1.6,1.6]);
 const film=t(t(solid(r.formed[0]).scale([1,1,-1])).translate([0,0,sheetZ+p.sheet]));
 scene('pressed',[actor('female',section(a.female)),actor('front',section(film)),actor('male',section(t(inverted.translate([0,0,closedZ]))))],[-1.8,-.8,.7]);
 const bottomClip=solid(r.formed.find(part=>part.id==='formed-bottom-clip')!);
 const bottomY=bottomClip.boundingBox().min[1];
 const lowerBox=t(t(M.Manifold.cube([14,12,8],true)).translate([0,bottomY+3,0]));
 const lf=t(a.front.intersect(lowerBox)),lb=t(t(a.back.scale([-1,1,-1])).intersect(lowerBox));
 scene('bottom-open',[actor('front',lf),actor('back',lb),actor('bottom-clip',t(bottomClip.translate([0,-9,0])))],[-1,-1.6,1],[[[0,bottomY-9,0],[0,bottomY,0]]]);
 scene('bottom-closed',[actor('front',lf),actor('back',lb),actor('bottom-clip',bottomClip)],[-1,-1.6,1]);
 scene('whole',r.formed.map(part=>actor(part.id.replace('formed-',''),part.mesh)),[-1,-1.6,.9]);
 mkdirSync('tmp/pdfs',{recursive:true});writeFileSync('tmp/pdfs/thermoform-figures.json',JSON.stringify(scenes));
 console.log(Object.keys(scenes).length+' viste reali del kit con mezzi filetti integrati.');
}finally{s.free();}
