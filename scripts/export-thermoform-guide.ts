/** Esporta le geometrie reali per le illustrazioni, senza ricostruire i pezzi a mano. */
import {mkdirSync,writeFileSync} from 'node:fs';
import {loadManifold,Scope,toMeshData,type Part,type Manifold,type MeshData} from '@bdl/geometry';
import {build} from '../apps/thermoform/src/geometry.ts';
import {DEFAULTS} from '../apps/thermoform/src/params.ts';
const M=await loadManifold(),s=new Scope(),t=<T extends {delete():void}>(a:T)=>s.t(a);
const p={...DEFAULTS,shape:'round' as const,width:63,height:71},r=build(M,p);
const colors:Record<string,string>={front:'#ff621d',back:'#efbe60',female:'#477e98',male:'#7eaabe',connector:'#477e98',cap:'#515e6c',lock:'#29a57c','bottom-clip':'#29a57c'};
const solid=(part:Part)=>{const mesh=new M.Mesh({numProp:3,vertProperties:part.mesh.positions,triVerts:part.mesh.indices});mesh.merge();return t(new M.Manifold(mesh));};
const actor=(id:string,m:Manifold|MeshData)=>{const mesh='volume' in m?toMeshData(m as Manifold):m as MeshData;return{id,color:colors[id]??'#477e98',positions:Array.from(mesh.positions),indices:Array.from(mesh.indices)};};
const a=Object.fromEntries(r.parts.map(part=>[part.id,solid(part)]));
const scenes:Record<string,unknown>={};
const scene=(name:string,items:ReturnType<typeof actor>[],eye=[-1,-1.6,1.1],arrows:number[][][]=[])=>scenes[name]={items,eye,arrows};
try{
 for(const part of r.parts)scene('part-'+part.id,[actor(part.id,a[part.id])]);
 scene('cap-under',[actor('cap',a.cap)],[-1,-1.6,-.9]);
 const neckY=Math.max(...Array.from(r.parts[0].mesh.positions).filter((_,i)=>i%3===1))-8;
 const front=t(t(a.front.rotate([90,0,0])).translate([0,0,-neckY-2]));
 const back=t(t(t(a.back.scale([1,1,-1])).rotate([90,0,0])).translate([0,0,-neckY-2]));
 const tabBox=t(t(M.Manifold.cube([14,8,14],true)).translate([0,0,1]));
 const ft=t(front.intersect(tabBox)),bt=t(back.intersect(tabBox));
 const pin=t(a.lock.translate([0,0,2.4]));
 const sectionBox=t(t(M.Manifold.cube([200,240,200],true)).translate([100,0,0]));
 const section=(m:Manifold)=>t(m.intersect(sectionBox));
 const connectorCut=section(a.connector);
 scene('tab-holes',[actor('front',t(ft.translate([0,-3,0]))),actor('back',t(bt.translate([0,3,0])))],[-1,-1.5,.65]);
 scene('tabs-in',[actor('connector',connectorCut),actor('front',ft),actor('back',bt)],[-1.6,-1,.75]);
 scene('pin-out',[actor('connector',connectorCut),actor('front',ft),actor('back',bt),actor('lock',t(pin.translate([0,-13,0])))],[-1.6,-1,.75],[[[0,-12,3],[0,-3,3]]]);
 scene('pin-in',[actor('connector',connectorCut),actor('front',ft),actor('back',bt),actor('lock',pin)],[-1.6,-1,.75]);
 scene('cap-down',[actor('connector',a.connector),actor('front',ft),actor('back',bt),actor('lock',pin),actor('cap',t(a.cap.translate([0,0,14])))],[-1.5,-1.8,.8],[[[0,0,14],[0,0,9]]]);
 scene('closed',[actor('connector',a.connector),actor('front',ft),actor('back',bt),actor('lock',pin),actor('cap',a.cap)],[-1,-1.6,.8]);
 const sheetZ=3+p.dome;
 const closedZ=6+p.dome+p.sheet+p.clearance;
 const inverted=t(a.male.rotate([0,180,0]));
 scene('exploded',[actor('female',a.female),actor('front',t(a.front.translate([0,0,sheetZ+15]))),actor('male',t(inverted.translate([0,0,closedZ+45])))],[-1,-1.6,.75],[[[0,0,44],[0,0,39]],[[0,0,32],[0,0,26]]]);
 scene('position',[actor('female',a.female),actor('front',t(a.front.translate([0,0,sheetZ])))],[-1,-1.6,1.6]);
 const formed=solid(r.formed[0]);
 const film=t(t(formed.scale([1,1,-1])).translate([0,0,sheetZ+p.sheet]));
 scene('pressed',[actor('female',section(a.female)),actor('front',section(film)),actor('male',section(t(inverted.translate([0,0,closedZ]))))],[-1.8,-.8,.7]);
 scene('release',[actor('female',a.female),actor('front',t(film.translate([0,0,22])))],[-1,-1.6,1.2],[[[0,0,20],[0,0,32]]]);
 const bottomY=Math.min(...Array.from(r.parts[0].mesh.positions).filter((_,i)=>i%3===1))+8;
 const lowerBox=t(t(M.Manifold.cube([18,14,20],true)).translate([0,bottomY-4,0]));
 const lowerFront=t(solid(r.formed[0]).intersect(lowerBox)),lowerBack=t(solid(r.formed[1]).intersect(lowerBox));
 const bottomClip=solid(r.formed.find(part=>part.id==='formed-bottom-clip')!);
 scene('bottom-open',[actor('front',lowerFront),actor('back',lowerBack),actor('bottom-clip',t(bottomClip.translate([0,-15,0])))],[-1,-1.6,1],[[[0,bottomY-16,0],[0,bottomY-8,0]]]);
 scene('bottom-closed',[actor('front',lowerFront),actor('back',lowerBack),actor('bottom-clip',bottomClip)],[-1,-1.6,1]);
 scene('whole',r.formed.map(part=>actor(part.id.replace('formed-',''),part.mesh)),[-1,-1.6,.9]);
 mkdirSync('tmp/pdfs',{recursive:true});writeFileSync('tmp/pdfs/thermoform-figures.json',JSON.stringify(scenes));
 console.log(Object.keys(scenes).length+' scene esportate dalla geometria reale del kit 63 × 71 mm.');
}finally{s.free();}
